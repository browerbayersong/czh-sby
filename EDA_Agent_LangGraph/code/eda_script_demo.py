"""A reviewed, deliberately narrow execution path for the generated counter script.

The existing fixed-template VCS runner is unchanged. This demo accepts exactly
three tool invocations and binds execution to the archived generated bytes.
"""
from __future__ import annotations

import hashlib
import json
import re
import shlex
import shutil
import stat
from datetime import datetime
from pathlib import Path
from typing import Any

from eda_analysis import _parse_sim_log
from eda_remote_v8 import (
    COVERAGE_METRICS, MAX_FILE_BYTES, RemoteError, SSHSettings, URG_BINARY,
    VCS_BINARY, _create_new_dir, _local_write, _parse_coverage, _read_remote_log,
    _sim_result, exec_checked, local_source_files, remote_job, ssh_connect,
)

SCRIPT = 'generated/scripts/run_vcs.sh'
RTL = 'generated/rtl/counter_8bit.v'
TB = 'generated/tb/tb_counter_8bit.v'
TOP = 'tb_counter_8bit'
STAGES = (
    ('compile', '300s', VCS_BINARY, '../build/vcs_compile.log'),
    ('simulate', '120s', '../build/simv', '../build/vcs_sim.log'),
    ('coverage', '120s', URG_BINARY, '../build/urg.log'),
)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def validate_script(text: str) -> dict[str, Any]:
    """Parse a tiny bash subset; reject additional commands rather than filter them."""
    if len(text.encode('utf-8')) > 16000 or '\x00' in text or '\r' in text:
        raise ValueError('脚本必须是 LF 换行的短文本')
    lines = text.replace('\\\n', ' ').splitlines()
    if not lines or lines[0] != '#!/bin/bash':
        raise ValueError('脚本首行必须是 #!/bin/bash')
    commands = [line.strip() for line in lines[1:]
                if line.strip() and not line.lstrip().startswith('#')]
    if len(commands) != 4 or commands[0] != 'set -euo pipefail':
        raise ValueError('只允许 set -euo pipefail 和三个依次执行的工具命令')
    parsed = []
    for line, (stage, seconds, executable, logfile) in zip(commands[1:], STAGES):
        match = re.fullmatch(r'(.+?)\s*>\s*(\.\./build/[a-z_]+\.log)\s+2>&1', line)
        if not match or match[2] != logfile:
            raise ValueError(f'{stage} 的日志重定向不符合约定')
        command = match[1].strip()
        if not re.fullmatch(r'''[A-Za-z0-9_./+=\-\s'"]+''', command):
            raise ValueError(f'{stage} 包含额外 shell 语法')
        tokens = shlex.split(command)
        if tokens[:3] != ['timeout', seconds, executable]:
            raise ValueError(f'{stage} 的工具路径或超时不符合约定')
        options: dict[str, str | bool] = {}
        sources = []
        flags = {'-full64', '-sverilog'} if stage == 'compile' else set()
        pairs = ({'-timescale=1ns/1ps': True} if stage == 'compile' else {})
        expected: dict[str, str | bool]
        if stage == 'compile':
            expected = {'-full64': True, '-sverilog': True, **pairs,
                        '-cm': COVERAGE_METRICS, '-cm_dir': '../build/cov.vdb',
                        '-top': TOP, '-o': '../build/simv'}
        elif stage == 'simulate':
            expected = {'-cm': COVERAGE_METRICS, '-cm_dir': '../build/cov.vdb'}
        else:
            expected = {'-dir': '../build/cov.vdb', '-format': 'text',
                        '-report': '../build/covReport'}
        index = 3
        while index < len(tokens):
            token = tokens[index]
            if stage == 'compile' and token in {RTL, TB}:
                if token in sources:
                    raise ValueError('编译源文件重复')
                sources.append(token)
            elif stage == 'compile' and token in {
                '+incdir+generated/rtl', '+incdir+generated/tb',
            }:
                if token in options:
                    raise ValueError('头文件目录重复')
                options[token] = True
            elif token in expected:
                if token in options:
                    raise ValueError(f'{stage} 参数重复：{token}')
                if token in flags or token in pairs:
                    options[token] = True
                else:
                    index += 1
                    if index >= len(tokens) or tokens[index] != expected[token]:
                        raise ValueError(f'{stage} 参数值不符合约定：{token}')
                    options[token] = tokens[index]
            else:
                raise ValueError(f'{stage} 存在未批准参数或路径：{token}')
            index += 1
        required = {k: v for k, v in options.items() if not k.startswith('+incdir+')}
        if required != expected or (stage == 'compile' and set(sources) != {RTL, TB}):
            raise ValueError(f'{stage} 缺少必需参数或源文件')
        parsed.append({'stage': stage, 'argv': tokens, 'log': logfile})
    return {'status': 'validated', 'sha256': digest(text.encode('utf-8')),
            'policy': 'counter-script-three-tools-v1', 'stages': parsed}


def local_preflight(workspace: Path) -> tuple[dict, dict[str, bytes]]:
    manifest = json.loads((workspace / 'generation_manifest.json').read_text(encoding='utf-8'))
    contents = {rel: path.read_bytes() for rel, path in local_source_files(workspace)}
    if set(contents) != {SCRIPT, RTL, TB}:
        raise ValueError('演示工作空间必须只包含已记录的 RTL、Testbench 和脚本')
    actual = {rel: digest(data) for rel, data in contents.items()}
    if actual != manifest['files_sha256']:
        raise ValueError('生成后文件有变动，请先重新审阅并记录')
    validation = validate_script(contents[SCRIPT].decode('utf-8'))
    if validation['sha256'] != manifest['script_review']['sha256']:
        raise ValueError('脚本与审阅记录不一致')
    return validation, contents


def classify_result(script_exit_code: int | None, sim_log: str, metrics: dict,
                    coverage: dict) -> str:
    if script_exit_code != 0:
        return 'script_failed'
    if _sim_result(0, sim_log) != 'passed_by_marker':
        return 'simulation_unverified_or_failed'
    if not (metrics.get('checks') == metrics.get('passed') == 2035
            and metrics.get('failed') == 0
            and metrics.get('functional_bins_hit') == metrics.get('functional_bins_total') == 14):
        return 'unexpected_test_result'
    return 'passed' if coverage.get('score') is not None else 'coverage_missing'


def run_script_demo(cfg: SSHSettings, workspace: Path, *, project: str,
                    remote_base: str, chat_id: str) -> dict[str, Any]:
    """Upload a snapshot, verify its bytes, then execute the actual reviewed .sh."""
    validation, contents = local_preflight(workspace)
    print('本地脚本审阅通过；正在上传独立工程快照…', flush=True)
    upload = remote_job(cfg, workspace, chat_id, mode='upload',
                        remote_base=remote_base, project_name=project)
    local = Path(upload['local_directory'])
    run_dir = upload['remote_directory']
    src_dir = upload['source_snapshot']
    build = run_dir + '/build'
    result: dict[str, Any] = {
        'mode': 'reviewed_generated_script', 'when': datetime.now().isoformat(timespec='seconds'),
        'status': 'not_executed', 'project_directory': upload['project_directory'],
        'remote_directory': run_dir, 'source_snapshot': src_dir,
        'local_directory': str(local), 'script': SCRIPT, 'script_review': validation,
        'files_sha256': {rel: digest(data) for rel, data in contents.items()},
        'stage_exit_codes': None,
    }
    ssh = None
    sftp = None
    build_created = False
    try:
        ssh = ssh_connect(cfg)
        sftp = ssh.open_sftp()
        # Verify every uploaded source, not only the executable shell text.
        for rel, data in contents.items():
            remote_path = src_dir + '/' + rel
            info = sftp.lstat(remote_path)
            if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_FILE_BYTES:
                raise RemoteError('远端源文件不是受控普通文件')
            with sftp.open(remote_path, 'rb') as source:
                uploaded = source.read(MAX_FILE_BYTES + 1)
            if uploaded != data:
                raise RemoteError(f'远端文件与本地审阅字节不一致：{rel}')
        _create_new_dir(sftp, build)
        build_created = True
        quote = shlex.quote
        syntax = (f'cd {quote(src_dir)} && bash -n {quote(SCRIPT)} '
                  '> ../build/script_syntax.log 2>&1')
        code, _, _ = exec_checked(ssh, syntax)
        result['syntax_exit_code'] = code
        if code != 0:
            result['status'] = 'syntax_failed'
        else:
            print('远端文件校验和语法检查通过；正在执行模型生成的脚本…', flush=True)
            command = (f'cd {quote(src_dir)} && timeout 570s bash -x {quote(SCRIPT)} '
                       '> ../build/script_execution.log 2>&1')
            result['execution_command'] = command
            code, _, _ = exec_checked(ssh, command, timeout_seconds=600)
            result['script_exit_code'] = code
    except (RemoteError, OSError) as exc:
        result.update(status='execution_error', error=str(exc))
    finally:
        # Preserve the script, review and partial logs even when one stage fails.
        _local_write(local, 'run_vcs.sh', contents[SCRIPT].decode('utf-8'))
        if build_created and sftp is not None:
            for remote_name, local_name in (
                ('script_syntax.log', 'script_syntax.log'),
                ('script_execution.log', 'script_execution.log'),
                ('vcs_compile.log', 'vcs_compile.log'),
                ('vcs_sim.log', 'vcs_sim.log'), ('urg.log', 'urg.log'),
                ('covReport/dashboard.txt', 'coverage_dashboard.txt'),
            ):
                try:
                    log = _read_remote_log(sftp, remote_name, build)
                except (RemoteError, OSError) as exc:
                    log = f'[日志回收失败：{exc}]'
                _local_write(local, local_name, log)
        metrics = _parse_sim_log(local / 'vcs_sim.log')
        dashboard = local / 'coverage_dashboard.txt'
        coverage = _parse_coverage(dashboard.read_text(encoding='utf-8')) if dashboard.exists() else {}
        result.update(metrics=metrics, coverage=coverage)
        if 'script_exit_code' in result:
            result['status'] = classify_result(result['script_exit_code'],
                (local / 'vcs_sim.log').read_text(encoding='utf-8'), metrics, coverage)
            if result['script_exit_code'] == 0:
                result['stage_exit_codes'] = {
                    'compile': 0, 'simulate': 0, 'coverage': 0,
                    'basis': 'set -euo pipefail; all three sequential commands completed',
                }
        summary = json.dumps(result, ensure_ascii=False, indent=2)
        _local_write(local, 'script_run_summary.json', summary)
        if sftp is not None:
            try:
                with sftp.open(run_dir + '/script_run_summary.json', 'wb') as target:
                    target.write(summary.encode('utf-8'))
            except OSError:
                pass  # Local evidence already saved.
            sftp.close()
        if ssh is not None:
            ssh.close()
    return result


def archive_script_demo(workspace: Path, result: dict, destination: Path) -> Path:
    """Create an additional allowlisted report package, including failed-run evidence."""
    destination.mkdir(parents=True, exist_ok=False)
    candidates = [(workspace / rel, rel) for rel in (SCRIPT, RTL, TB)]
    candidates += [(workspace / name, name) for name in (
        'generation_request.txt', 'generation_result.json', 'generation_manifest.json',
        'llm_trace.jsonl', 'local_bash_syntax.log', 'README.md',
    )]
    run = Path(result['local_directory'])
    candidates += [(run / name, '运行日志/' + name) for name in (
        'run_vcs.sh', 'run_summary.json', 'script_run_summary.json', 'script_syntax.log',
        'script_execution.log', 'vcs_compile.log', 'vcs_sim.log', 'urg.log', 'coverage_dashboard.txt',
    )]
    candidates += [(Path(__file__).with_name(name), '项目实现/' + name) for name in (
        'eda_script_demo.py', 'generate_script_demo.py', 'run_generated_script.py', 'test_script_demo.py',
    )]
    hashes = {}
    for source, relative in candidates:
        if not source.exists():
            continue
        if not source.is_file() or source.is_symlink():
            raise ValueError('归档源文件不是普通文件')
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        hashes[relative] = digest(target.read_bytes())
    index = (
        '# 模型生成仿真脚本：补充实验\n\n'
        f"本次真实运行状态：{result['status']}。\n\n"
        '脚本经实际 DeepSeek API 和 LangGraph 生成，原始文本响应见 llm_trace.jsonl；'
        'JSON 规划及静态复查结果见 generation_result.json。没有改动已通过的计数器 RTL/TB。\n\n'
        '执行链：本地审阅 → 独立快照上传 → 源文件字节校验 → bash -n → '
        '实际执行 generated/scripts/run_vcs.sh → 回收原始日志 → 解析检查点与覆盖率。\n\n'
        '运行日志/script_execution.log 是 bash -x 的实际命令轨迹；'
        'script_run_summary.json 是本实验结果；run_summary.json 仅记录前置上传。\n\n'
        '报告应区分脚本生成、本地静态检查和 Linux 实际执行；失败日志也保留，'
        '不能将脚本退出码单独当作功能正确性证据。覆盖率是 Testbench 顶层统计口径。\n'
    )
    _local_write(destination, '先看这里.md', index)
    hashes['先看这里.md'] = digest((destination / '先看这里.md').read_bytes())
    _local_write(destination, 'SHA256SUMS.json', json.dumps(hashes, ensure_ascii=False, indent=2))
    shutil.make_archive(str(destination), 'zip', root_dir=destination)
    return destination
